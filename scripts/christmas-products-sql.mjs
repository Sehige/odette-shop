// Puts the Christmas offer (src/data/christmas.js) in the shop: writes the SQL that adds the
// products to Supabase, and copies their photos to public/foto/craciun/ so each product has a
// fixed image address on the site. Run it after updating christmas.js each November:
//
//   node scripts/christmas-products-sql.mjs
//
// then deploy the site (the photos must be live first) and run the SQL file it names in
// Supabase → SQL Editor. Products already in the shop all year are left out (SKIP).
import fs from 'node:fs';
import path from 'node:path';
import { christmas } from '../src/data/christmas.js';

const SITE = 'https://www.odette-confiserie.ro';
const PHOTOS = 'public/foto/craciun';
const CATEGORY = { slug: 'produse-de-craciun', name_ro: 'Produse de Crăciun', name_en: 'Christmas products' };
// the unused "Cutii de Craciun" category, renamed and reused
const OLD_CATEGORY_ID = '8ac926ca-abc5-44dc-8c7d-5aae733e5844';
// On the Christmas page, but already in the shop under their own name
const SKIP = {
  'babka-cu-mac': 'Babka cu mac',
  'babka-cu-nuca': 'Babka cu nucă',
  'babka-cu-fistic': 'Babka cu fistic',
  'madeleine-asortate': 'Pachet Madeleine asortate',
  saratele: 'Sărățele cu semințe',
};

const sql = (value) => (value === null || value === undefined ? 'null' : typeof value === 'number' ? String(value) : `'${String(value).replace(/'/g, "''")}'`);
const days = (key) => christmas.pickup.map((p) => p[key]).join(key === 'days' ? ' sau ' : ' or ');
const offerRo = `Din oferta de Crăciun: comenzi până pe ${christmas.orderBy}, cu ridicare sau livrare pe ${days('days')}.`;
const offerEn = `From our Christmas offer: orders until ${christmas.orderByEn}, with pickup or delivery on ${days('daysEn')}.`;
const largest = (section) => (section.layout === 'large' ? 1200 : 800);

const rows = [];
fs.mkdirSync(PHOTOS, { recursive: true });
for (const section of christmas.sections) {
  for (const item of section.items) {
    if (SKIP[item.id]) continue;
    fs.copyFileSync(path.join('src/assets/christmas', `${item.image}-${largest(section)}.webp`), path.join(PHOTOS, `${item.image}.webp`));
    const image = `${SITE}/foto/craciun/${item.image}.webp`;
    // the section's intro speaks for its products, except for one sold by the piece among those sold by weight
    const byWeight = section.id === 'la-gramaj';
    const intro = !byWeight || item.per === '100 g';
    const describe = (box, en) => {
      const text = en ? item.descriptionEn || (intro && section.introEn) : item.description || (intro && section.intro);
      const contents = en ? box.contentsEn : box.contents;
      return [text, contents && `${en ? 'Contents' : 'Conține'}: ${contents.join(', ')}.`, en ? offerEn : offerRo].filter(Boolean).join(' ');
    };
    const quantity = (box) =>
      box.weight ? [box.weight, box.pieces && `${box.pieces} buc`].filter(Boolean).join(' · ') : byWeight && box.per === '100 g' ? 'pachete de 100 g, 500 g sau 1 kg' : null;
    // "18 lei/100 g", "169 lei/cutie", "19 lei/borcan", "80 lei/buc"
    const unit = (box) => box.per || (section.id === 'camara' ? 'borcan' : box.pieces ? 'cutie' : 'buc');
    for (const box of item.variants || [item]) {
      rows.push({
        slug: item.variants ? `${item.id}-${box.name.toLowerCase().replace(/\s+/g, '-')}` : item.id,
        name_ro: item.variants ? `${item.name} – ${box.name}` : item.name,
        name_en: item.variants ? `${item.nameEn} – ${box.nameEn}` : item.nameEn || item.name,
        description_ro: describe(box, false),
        description_en: describe(box, true),
        price: box.price,
        price_unit: unit(box),
        quantity: quantity(box),
        image_url: image,
      });
    }
  }
}

const values = rows
  .map((r, i) => `    (${[r.slug, r.name_ro, r.name_en, r.description_ro, r.description_en, r.price, r.price_unit, r.quantity, i + 1, r.image_url].map(sql).join(', ')})`)
  .join(',\n');

const file = `supabase/sql/${new Date().toISOString().slice(0, 10)}_christmas_products.sql`;
fs.writeFileSync(file, `-- Christmas ${christmas.year} products in the shop — Odette Confiserie
--
-- Generated by scripts/christmas-products-sql.mjs from src/data/christmas.js (do not edit by hand).
-- Run once in Supabase → SQL Editor, after the site with public/foto/craciun is live (the
-- photos). It is safe to run again. The site rebuilds by itself a few minutes later.
--
-- - Category "${CATEGORY.name_ro}" (the unused "Cutii de Craciun" one, renamed), first in the shop.
-- - ${rows.length} products, one per box size, in the order of the /craciun page. A product that already
--   exists with the same slug but is switched off is updated and switched on (its ingredients,
--   allergens and photo are kept); one that is already on is left as it is.
-- - Left out, already in the shop all year: ${Object.values(SKIP).join(', ')}.
-- - Ingredients and allergens are empty: add them in the admin before customers order online.
--
-- After the holidays, switch the whole offer off with:
--   update public.products set "isActive" = false
--   where category = (select id from public.categories where slug = '${CATEGORY.slug}');

begin;

update public.categories
set name_ro = ${sql(CATEGORY.name_ro)}, name_en = ${sql(CATEGORY.name_en)}, slug = ${sql(CATEGORY.slug)}, order_index = 0,
    intro_ro = ${sql(`Oferta de Crăciun și Revelion ${christmas.year}. ${offerRo.replace('Din oferta de Crăciun: c', 'C')}`)},
    intro_en = ${sql(`Our Christmas and New Year ${christmas.year} offer. ${offerEn.replace('From our Christmas offer: o', 'O')}`)}
where id = '${OLD_CATEGORY_ID}';

insert into public.categories (id, name_ro, name_en, slug, order_index, "isFeatured")
select gen_random_uuid(), ${sql(CATEGORY.name_ro)}, ${sql(CATEGORY.name_en)}, ${sql(CATEGORY.slug)}, 0, false
where not exists (select 1 from public.categories where slug = ${sql(CATEGORY.slug)});

insert into public.products as p
  (id, slug, name_ro, name_en, description_ro, description_en, price, price_unit, quantity,
   order_index, image_url, category, "isActive", best_seller_flag, "isVegetarian")
select gen_random_uuid(), v.slug, v.name_ro, v.name_en, v.description_ro, v.description_en, v.price, v.price_unit, v.quantity,
       v.order_index, v.image_url, (select id from public.categories where slug = ${sql(CATEGORY.slug)}), true, false, false
from (values
${values}
  ) as v(slug, name_ro, name_en, description_ro, description_en, price, price_unit, quantity, order_index, image_url)
on conflict (slug) do update set
  name_ro = excluded.name_ro, name_en = excluded.name_en,
  description_ro = excluded.description_ro, description_en = excluded.description_en,
  price = excluded.price, price_unit = excluded.price_unit, quantity = excluded.quantity,
  order_index = excluded.order_index, image_url = coalesce(p.image_url, excluded.image_url),
  category = excluded.category, "isActive" = true
where not p."isActive";

commit;

-- Check: the offer as the shop will show it
select p.order_index, p.slug, p.name_ro, p.price, p.price_unit, p.quantity, p."isActive"
from public.products p
join public.categories c on c.id = p.category
where c.slug = ${sql(CATEGORY.slug)}
order by p.order_index;
`);
console.log(`${file}: ${rows.length} products; photos in ${PHOTOS}`);
